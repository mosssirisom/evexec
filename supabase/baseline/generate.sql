-- Returns the structure of the live database as rows of SQL, in the order
-- assemble.py writes them into schema.sql. Read-only. Covers schemas public and
-- private, policies on storage, and triggers on auth/storage that call our
-- functions. Leaves out data, secrets and scheduled jobs (names only).
with ns as (select oid, nspname from pg_namespace where nspname in ('public','private')),
rel as (select c.oid, n.nspname, c.relname, c.relkind, c.relacl, c.relowner, c.relrowsecurity, c.reloptions, format('%I.%I', n.nspname, c.relname) as fq
        from pg_class c join ns n on n.oid=c.relnamespace
        where not exists (select 1 from pg_depend d where d.objid=c.oid and d.deptype='e')),
idseq as (select d.objid from pg_depend d where d.deptype='i' and d.classid='pg_class'::regclass and d.refclassid='pg_class'::regclass),
fn as (select p.oid, n.nspname, p.proname, p.proacl, p.proowner, p.prokind from pg_proc p join ns n on n.oid=p.pronamespace
       where p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e'))
select * from (
 select 10 as ord, 'schema' as kind, nspname::text as name, format('create schema if not exists %I;', nspname) as ddl from ns where nspname <> 'public'
 union all
 select 20, 'sequence', r.fq, format('create sequence %s as %s increment by %s minvalue %s maxvalue %s start with %s cache %s%s;', r.fq, s.data_type, s.increment_by, s.min_value, s.max_value, s.start_value, s.cache_size, case when s.cycle then ' cycle' else '' end)
   from rel r join pg_sequences s on s.schemaname=r.nspname and s.sequencename=r.relname where r.relkind='S' and r.oid not in (select objid from idseq)
 union all
 select 30, 'table', r.fq, format(E'create table %s (\n  %s\n);', r.fq, (
     select string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case when a.attidentity='a' then ' generated always as identity' when a.attidentity='d' then ' generated by default as identity' else '' end
        || case when a.attidentity='' and ad.adbin is not null then ' default '||pg_get_expr(ad.adbin, ad.adrelid) else '' end
        || case when a.attnotnull then ' not null' else '' end, E',\n  ' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid=a.attrelid and ad.adnum=a.attnum
     where a.attrelid=r.oid and a.attnum>0 and not a.attisdropped))
   from rel r where r.relkind='r'
 union all
 select 35, 'seq_owned', r.fq, format('alter sequence %s owned by %I.%I.%I;', r.fq, tn.nspname, t.relname, a.attname)
   from rel r join pg_depend d on d.objid=r.oid and d.deptype='a' and d.classid='pg_class'::regclass and d.refclassid='pg_class'::regclass
   join pg_class t on t.oid=d.refobjid join pg_namespace tn on tn.oid=t.relnamespace join pg_attribute a on a.attrelid=t.oid and a.attnum=d.refobjsubid
   where r.relkind='S'
 union all
 select case when k.contype='f' then 45 else 40 end, 'constraint', r.fq||'.'||k.conname, format('alter table only %s add constraint %I %s;', r.fq, k.conname, pg_get_constraintdef(k.oid))
   from pg_constraint k join rel r on r.oid=k.conrelid where k.contype in ('p','u','c','x','f') and r.relkind='r'
 union all
 select 50, 'index', format('%I.%I', i.schemaname, i.indexname), i.indexdef||';'
   from pg_indexes i join ns on ns.nspname=i.schemaname join pg_class ic on ic.relname=i.indexname and ic.relnamespace=ns.oid
   where not exists (select 1 from pg_constraint k where k.conindid=ic.oid)
 union all
 select 60, 'function', f.oid::regprocedure::text, pg_get_functiondef(f.oid)||';' from fn f
 union all
 select 70, 'view', r.fq, format('create view %s%s as %s', r.fq, case when r.reloptions is not null then ' with ('||array_to_string(r.reloptions, ', ')||')' else '' end, pg_get_viewdef(r.oid, true))
   from rel r where r.relkind='v'
 union all
 select 80, 'trigger', format('%I.%I.%I', tn.nspname, tc.relname, t.tgname), pg_get_triggerdef(t.oid)||';'
   from pg_trigger t join pg_class tc on tc.oid=t.tgrelid join pg_namespace tn on tn.oid=tc.relnamespace
   where not t.tgisinternal and (tn.nspname in ('public','private') or (tn.nspname in ('auth','storage') and t.tgfoid in (select oid from fn)))
 union all
 select 90, 'rls', r.fq, format('alter table %s enable row level security;', r.fq) from rel r where r.relkind='r' and r.relrowsecurity
 union all
 select 95, 'policy', format('%I.%I.%I', p.schemaname, p.tablename, p.policyname),
   format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
     (select string_agg(case when x::text='public' then 'public' else quote_ident(x::text) end, ', ') from unnest(p.roles) x),
     case when p.qual is not null then E'\n  using ('||p.qual||')' else '' end,
     case when p.with_check is not null then E'\n  with check ('||p.with_check||')' else '' end)
   from pg_policies p where p.schemaname in ('public','private','storage')
 union all
 select 100, 'acl_schema', n.nspname::text, format('revoke all on schema %I from public, anon, authenticated, service_role;', n.nspname) from ns n where n.nspname <> 'public'
 union all
 select 101, 'acl_schema', n.nspname::text, format('grant %s on schema %I to %s;', string_agg(a.privilege_type, ', ' order by a.privilege_type), n.nspname, case when a.grantee=0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)::text) end)
   from pg_namespace n, aclexplode(n.nspacl) a where n.nspname in ('public','private') and a.grantee <> n.nspowner group by n.nspname, a.grantee
 union all
 select 110, 'acl_rel', r.fq, format('revoke all on %s %s from public, anon, authenticated, service_role;', case when r.relkind='S' then 'sequence' else 'table' end, r.fq) from rel r where r.relkind in ('r','v','S')
 union all
 select 111, 'acl_rel', r.fq, format('grant %s on %s %s to %s;', string_agg(a.privilege_type, ', ' order by a.privilege_type), case when r.relkind='S' then 'sequence' else 'table' end, r.fq, case when a.grantee=0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)::text) end)
   from rel r, aclexplode(r.relacl) a where r.relkind in ('r','v','S') and a.grantee <> r.relowner group by r.fq, r.relkind, a.grantee
 union all
 select 120, 'acl_fn', f.oid::regprocedure::text, format('revoke all on %s %s from %s;', case when f.prokind='p' then 'procedure' else 'function' end, f.oid::regprocedure, case when f.proacl is null then 'anon, authenticated, service_role' else 'public, anon, authenticated, service_role' end) from fn f
 union all
 select 121, 'acl_fn', f.oid::regprocedure::text, format('grant execute on %s %s to %s;', case when f.prokind='p' then 'procedure' else 'function' end, f.oid::regprocedure, case when a.grantee=0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)::text) end)
   from fn f, aclexplode(f.proacl) a where a.grantee <> f.proowner
 union all
 select 130, 'default_acl', coalesce(n.nspname::text,'(all)')||'.'||d.defaclobjtype::text||'.'||pg_get_userbyid(d.defaclrole)::text,
   format('-- live: for role %s%s, %s: %s', pg_get_userbyid(d.defaclrole), coalesce(' in schema '||n.nspname::text, ''), d.defaclobjtype::text, d.defaclacl::text)
   from pg_default_acl d left join pg_namespace n on n.oid=d.defaclnamespace where n.nspname is null or n.nspname in ('public','private')
 union all
 select 140, 'publication', schemaname||'.'||tablename, format('alter publication supabase_realtime add table %I.%I;', schemaname, tablename) from pg_publication_tables where pubname='supabase_realtime'
 union all
 select 150, 'bucket', b.id, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %s) on conflict (id) do nothing;', b.id, b.name, b.public, coalesce(b.file_size_limit::text,'null'), coalesce(quote_literal(b.allowed_mime_types::text)||'::text[]','null')) from storage.buckets b
 union all
 select 160, 'cron_name', j.jobname::text, format('-- cron job (not created by the baseline): %s  schedule %s', j.jobname, j.schedule) from cron.job j
) q order by ord, name, ddl;
